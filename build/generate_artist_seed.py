def main() -> None:
    root = Path(__file__).resolve().parents[1]
    out = root / "data" / "seeds" / "known_artists.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    seen: set[str] = set()
    lines: list[str] = [
        "# Registro bootstrap artisti — KaraokeManager",
        "# Un artista/band per riga. Rigenerabile con: python build/generate_artist_seed.py",
        "",
    ]
    for name in ARTISTS:
        key = name.strip().casefold()
        if not key or key in seen:
            continue
        seen.add(key)
        lines.append(name.strip())
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Scritti {len(seen)} artisti in {out}")


if __name__ == "__main__":
    main()
